"""Абстракция получения маски объекта — не завязана на конкретный backend. См. докстринг пакета
(`__init__.py`) про причину: сама модель (SAM3) сейчас вызывается subprocess'ом к соседнему
Windows-проекту, но при переносе в WSL/Webots-симулятор должно быть достаточно подставить другую
реализацию `SegmentationBackend`, не трогая вызывающий код диалога."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol

import numpy as np


@dataclass
class SegmentationResult:
    mask: np.ndarray  # (H, W) bool — True внутри объекта; в разрешении исходного изображения,
    # САМАЯ уверенная детекция на кадре (см. `all_masks` ниже про остальные) — используется для
    # классификации региона и 3D-реконструкции, поведение не изменилось с тех пор, как backend
    # отдавал только одну детекцию.
    confidence: float
    class_name: str
    # "belt"/"mirror"/None — откуда физически эта детекция (центроид маски против проекции
    # меток ленты/зеркала, см. gui/dialogs/photo_capture_dialog.py::_classify_segmentation_region
    # и segmentation/region_filter.py). None — поза недоступна или маска вне обеих областей.
    # ВАЖНО: 3D-реконструкция (pose_carving) сейчас понимает только ПРЯМУЮ позу камеры — маска
    # отражения ("mirror"), поданная вместе с прямой позой, даёт геометрически бессмысленное
    # ограничение (полупространства не пересекаются) и ломает результат для ВСЕГО набора фото,
    # не только этого кадра. Поэтому в реконструкцию должны идти только маски region="belt" (см.
    # PhotoCaptureDialog._ready_items) — отражение показываем в превью, но не используем для 3D,
    # пока нет отдельной "зеркальной" геометрии позы камеры.
    region: str | None = None
    # ВСЕ маски, найденные SAM3 на этом кадре, по убыванию уверенности — `all_masks[0] is mask`
    # (тот же массив). Показ пользователю (выключение чекбокса "Скрывать объекты вне ленты"
    # раньше не показывало другие объекты — backend отдавал только лучшую детекцию, снято) и
    # сырьё для геометрического отбора кандидатов ниже. Пустой список — backend не поддерживает
    # мульти-детекцию (не текущий `Sam3SubprocessBackend`, задел на другую реализацию).
    all_masks: list[np.ndarray] = field(default_factory=list)
    # Кандидаты для 3D-реконструкции: подсписок `all_masks` (тот же порядок — по убыванию
    # уверенности), прошедший геометрический фильтр области (`region_filter.
    # select_region_candidates` — внутри ожидаемого региона, не "фон целиком"). Заполняется
    # `PhotoCaptureDialog._on_segmentation_finished` для region="belt"/"mirror"; `mask` выше
    # при этом ЗАМЕНЯЕТСЯ на candidates[0] (самый уверенный ГЕОМЕТРИЧЕСКИ ВАЛИДНЫЙ, а не просто
    # самый уверенный — SAM3 с промптом-существительным уверенно детектит и фон/чужие объекты).
    # Хвост списка использует консенсусная реконструкция (`pose_carving.carve_consensus`):
    # кандидат, противоречащий остальным ракурсам, заменяется следующим, а не роняет всё.
    candidates: list[np.ndarray] = field(default_factory=list)


class SegmentationBackend(Protocol):
    def segment_batch(
        self, images_bgr: list[np.ndarray], prompt: str | None = None
    ) -> list[SegmentationResult | None]:
        """Один результат на входное изображение, в том же порядке. `None` на конкретной позиции
        — объект не найден или ошибка по этому фото (не должно прерывать обработку остальных).
        `prompt=None` — использовать промпт по умолчанию из конфигурации backend'а."""
        ...

    def shutdown(self) -> None:
        """Останавливает фоновый процесс/ресурс backend'а (модель выгружается). Вызывающая
        сторона держит backend живым между вызовами `segment_batch()` (загрузка модели не
        мгновенная) и вызывает `shutdown()` только при закрытии приложения."""
        ...
