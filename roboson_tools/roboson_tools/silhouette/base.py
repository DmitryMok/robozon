"""Общий интерфейс построения силуэта — не зависит от режима (Analytical/Camera).

Ключевое требование ТЗ: на уровне этого интерфейса не существует понятий камеры, зеркала,
объектива, фокусного расстояния, перспективы, освещения — только направление наблюдения.

Конвенция осей (см. `geometry/transform.py`): view_angle — азимутальный угол вокруг
продольной оси X ("roll axis" — направление движения объекта по конвейеру, вдоль которого
сохраняется поперечное сечение). Камеры/зеркало физически образуют кольцо вокруг этой оси и
смотрят на объект сбоку, поперёк направления движения — именно это моделирует view_angle.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

import numpy as np

from ..geometry.mesh_io import Mesh


@dataclass
class Silhouette:
    """Бинарная маска силуэта + параметры перевода пикселей в мировые координаты.

    Строка растра `row` соответствует мировой координате X (позиция вдоль продольной/roll оси);
    столбец `col` — координате вдоль поперечной оси силуэта r_theta (лежит в плоскости Y-Z).
    Масштаб (px_per_unit) одинаков по обеим осям, чтобы не искажать геометрию при измерениях.
    """

    mask: np.ndarray  # (H, W) bool — True внутри силуэта
    view_angle_deg: float  # азимутальный угол наблюдения вокруг продольной оси X
    u_min: float  # мировая координата вдоль r_theta, соответствующая столбцу 0
    axis_min: float  # мировая координата X, соответствующая нижней строке маски
    px_per_unit: float  # масштаб растра (px на единицу длины меша)
    # Субпиксельная (мягкая) маска — доля площади пикселя внутри силуэта, float32 [0..1],
    # той же формы, что mask. Заполняется только Camera Mode при supersample > 1 (см.
    # silhouette/camera.build_silhouette): локализует границу с точностью ~1/S px вместо
    # ±0.5px бинарной маски. None — обычный бинарный режим (mask остаётся источником истины).
    coverage: np.ndarray | None = None
    # Крупнейший внешний контур силуэта с субпиксельной точностью (float (N,2), [col, row] в
    # НАТИВНЫХ пиксельных координатах маски): извлечён на тонкой сетке супсемплинга до
    # усреднения, поэтому граница локализована с точностью ~1/S px. None — бинарный режим
    # (потребители падают обратно на cv2.findContours по mask).
    contour_px: np.ndarray | None = None
    # Оптический центр кадра в координатах маски (col, row). Заполняется только в Camera Mode
    # при `build_silhouette(crop_to_object=True)` — обрезке кадра до bbox маски + margin
    # (см. silhouette/camera.build_silhouette): вместо растеризации в полный кадр 512²/1024²,
    # где объект может занимать <1% площади (тонкая ручка, объект на start/end у края), маска
    # обрезается до региона объекта. При этом `cx`/`cy` уже не `cols/2`/`rows/2` (центр
    # обрезанной маски), а смещение старого оптического центра полного кадра в координатах
    # обрезанной маски — это позволяет конусным методам (polytope_hull/exact_polyhedral_hull/
    # voxel_carving) корректно проектировать воксели/точки в обрезанную маску. None —
    # ортографика (Analytical Mode, не используется в Camera Mode) или старое поведение
    # `crop_to_object=False` (маска полного кадра, cx/cy = cols/2 / rows/2, как считает
    # `camera_frame`). Конусные методы должны использовать `silhouette.cx`/`silhouette.cy`,
    # если они не None, вместо пересчёта через `camera_frame`.
    cx: float | None = None
    cy: float | None = None


class SilhouetteProvider(Protocol):
    """Абстракция над способом получения силуэта."""

    def build(self, mesh: Mesh, view_angle_deg: float, resolution_px: int) -> Silhouette: ...
